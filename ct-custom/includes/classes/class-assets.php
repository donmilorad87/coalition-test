<?php
/**
 * Front-end and editor asset loading.
 *
 * @package CtCustom
 */

namespace CtCustom;

defined( 'ABSPATH' ) || exit;

/**
 * Enqueues the wp-scripts build output and the Customizer CSS variables.
 * Fonts come from the WordPress Font Library (see Fonts).
 */
final class Assets {

	/**
	 * Register hooks.
	 */
	public static function start(): void {
		add_action( 'wp_enqueue_scripts', array( self::class, 'enqueue_front' ) );
		add_action( 'enqueue_block_editor_assets', array( self::class, 'enqueue_editor' ) );
		add_filter( 'block_editor_settings_all', array( self::class, 'editor_inline_styles' ) );
	}

	/**
	 * Enqueue a build/<name>.js entry with its generated dependency list.
	 *
	 * @param string   $name       Entry name.
	 * @param string[] $extra_deps Additional dependencies.
	 * @return string Script handle.
	 */
	public static function enqueue_build_script( string $name, array $extra_deps = array() ): string {
		$asset  = self::asset( $name );
		$handle = 'ct-custom-' . $name;

		wp_enqueue_script(
			$handle,
			get_theme_file_uri( "build/{$name}.js" ),
			array_merge( $asset['dependencies'], $extra_deps ),
			$asset['version'],
			array(
				'in_footer' => true,
				'strategy'  => 'defer',
			)
		);
		return $handle;
	}

	/**
	 * Theme CSS + inline variables/fonts, and the navigation script.
	 */
	public static function enqueue_front(): void {
		$asset = self::asset( 'front' );
		wp_enqueue_style( 'ct-custom-front', get_theme_file_uri( 'build/front.css' ), array(), $asset['version'] );
		wp_add_inline_style( 'ct-custom-front', Customizer_Css::root_css() );

		self::enqueue_build_script( 'front' );
	}

	/**
	 * Block editor: page options panel + default values for block inspector placeholders.
	 */
	public static function enqueue_editor(): void {
		$handle = self::enqueue_build_script( 'editor' );
		// Allow-list only what the blocks read: editors of any role see this, SMTP credentials must never be in it.
		$defaults = array_intersect_key(
			Settings::sanitize( get_option( Settings::OPTION, Settings::defaults() ) ),
			array_flip( array( 'company', 'address', 'phone', 'fax', 'socials' ) )
		);

		// Thumbnail URLs let the Social Links block preview Theme Settings items it copies.
		foreach ( $defaults['socials'] as &$item ) {
			$item['image_url'] = $item['image_id'] ? (string) wp_get_attachment_image_url( $item['image_id'], 'thumbnail' ) : '';
		}
		unset( $item );
		wp_add_inline_script( $handle, 'window.ctCustomDefaults = ' . wp_json_encode( $defaults ) . ';', 'before' );
	}

	/**
	 * Make the CSS variables available inside the (iframed) editor canvas.
	 *
	 * @param array $settings Editor settings.
	 * @return array
	 */
	public static function editor_inline_styles( array $settings ): array {
		$settings['styles'][] = array(
			'css' => str_replace( ':root{', ':root,.editor-styles-wrapper{', Customizer_Css::root_css() ),
		);
		return $settings;
	}

	/**
	 * Read build/<name>.asset.php generated by wp-scripts.
	 *
	 * @param string $name Entry name.
	 * @return array{dependencies: string[], version: string}
	 */
	private static function asset( string $name ): array {
		$file = CT_CUSTOM_BUILD . $name . '.asset.php';
		if ( ! is_readable( $file ) ) {
			// Missing build is a developer error; log it and degrade to an unversioned, dependency-free load.
			error_log( "ct-custom: missing {$file}, run `npm run build`." ); // phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_error_log
			return array(
				'dependencies' => array(),
				'version'      => CT_CUSTOM_VERSION,
			);
		}
		return require $file;
	}
}
